"""Item list for the Fabricator editor (Tools/fabricator_editor.html).

Writes Tools/fabricator_catalog.js: every item Survival's Craftbot (or Saw
Table, for wedges) can craft, with its name, English title, icon cell and
whether Survival unlocks it from the start. Run it again after a game update
(plain Python, no extra libraries):

    python Tools/make_fabricator_catalog.py
"""
import json, os, re

GAME = r"D:\steam\steamapps\common\Scrap Mechanic"
HERE = os.path.dirname(os.path.abspath(__file__))
SURVIVAL = os.path.join(GAME, "Survival")
DATA = os.path.join(GAME, "Data")


def read_json(path):
    # (Survival's files have // comments: whole lines, and after values)
    text = open(path, encoding="utf-8-sig").read()
    lines = []
    for line in text.split("\n"):
        # (cut at a // that isn't inside a "string")
        inside = False
        for i, ch in enumerate(line):
            if ch == '"' and (i == 0 or line[i - 1] != "\\"):
                inside = not inside
            elif ch == "/" and not inside and line[i + 1:i + 2] == "/":
                line = line[:i]
                break
        lines.append(line)
    return json.loads("\n".join(lines))


# Internal names: survival_items.lua (name = sm.uuid.new( "uuid" ))
names = {}
for line in open(os.path.join(SURVIVAL, "Scripts", "game", "survival_items.lua"), encoding="utf-8"):
    m = re.match(r'\s*(\w+)\s*=\s*sm\.uuid\.new\(\s*"([0-9a-f-]+)"', line)
    if m:
        names[m.group(2)] = m.group(1)

# Titles (English)
titles = {}
for path in (os.path.join(DATA, "Gui", "Language", "English", "InventoryItemDescriptions.json"),
             os.path.join(SURVIVAL, "Gui", "Language", "English", "inventoryDescriptions.json")):
    if os.path.exists(path):
        for uuid, entry in read_json(path).items():
            if isinstance(entry, dict) and entry.get("title"):
                titles[uuid] = entry["title"]

# Craftbot recipes, then the Saw Table's (wedges)
recipes = []
folder = os.path.join(SURVIVAL, "CraftingRecipes", "craftbot")
for path in read_json(os.path.join(folder, "craftbot.json")).values():
    path = path.replace("$SURVIVAL_DATA", SURVIVAL)
    for recipe in read_json(path):
        recipes.append((recipe["itemId"], "craftbot"))
for recipe in read_json(os.path.join(SURVIVAL, "CraftingRecipes", "sawtable.json")):
    recipes.append((recipe["itemId"], "sawtable"))

# Unlocked from the start (RecipeManager's DefaultUnlockedItems)
rm = open(os.path.join(SURVIVAL, "Scripts", "game", "managers", "RecipeManager.lua"), encoding="utf-8").read()
block = rm[rm.index("DefaultUnlockedItems = {"):]
block = block[:block.index("\n}")]
default_names = set(re.findall(r"ITEMS\.(\w+)", block))

# Icons: which icon map and cell (the editor shows them straight from the game folder)
icons = {}
maps = []
for path in (os.path.join(SURVIVAL, "Gui", "IconMapSurvival.xml"), os.path.join(DATA, "Gui", "IconMap.xml"), os.path.join(DATA, "Gui", "ToolIconMap.xml")):
    text = open(path, encoding="utf-8-sig").read()
    for group in re.finditer(r'<Group[^>]*texture="([^"]+)"[^>]*size="(\d+) (\d+)"[^>]*>(.*?)</Group>', text, re.S):
        texture = os.path.join(os.path.dirname(path), group.group(1))
        index = len(maps)
        maps.append({"file": "file:///" + texture.replace("\\", "/").replace(" ", "%20"), "size": int(group.group(2))})
        for m in re.finditer(r'<Index name="([^"]+)">\s*<Frame point="(\d+) (\d+)"', group.group(4)):
            icons.setdefault(m.group(1), [index, int(m.group(2)), int(m.group(3))])

items = []
seen = set()
for uuid, bench in recipes:
    if uuid in seen:
        continue
    seen.add(uuid)
    name = names.get(uuid, "")
    items.append({
        "uuid": uuid, "name": name, "title": titles.get(uuid, name or uuid),
        "bench": bench, "default": name in default_names, "icon": icons.get(uuid),
    })
items.sort(key=lambda i: i["title"].lower())

out = os.path.join(HERE, "fabricator_catalog.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by make_fabricator_catalog.py: items the Craftbot or Saw Table can craft.\n")
    f.write("const ICON_MAPS = " + json.dumps(maps) + ";\n")
    f.write("const CATALOG = [\n")
    for item in items:
        f.write("\t" + json.dumps(item) + ",\n")
    f.write("];\n")
print(len(items), "items,", sum(1 for i in items if i["default"]), "unlocked from the start ->", out)
